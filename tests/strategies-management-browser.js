(async () => {
  const checks = [];
  function check(name, condition) { checks.push({name, passed: !!condition}); if (!condition) throw new Error(name); }
  async function waitFor(fn) { for (let i=0;i<200;i++) { const value=fn(); if(value)return value; await new Promise(r=>setTimeout(r,25)); } throw new Error('UI did not become ready'); }
  const DN = window.DN;
  await waitFor(() => document.querySelector('#unit-grid input'));
  window.confirm = () => true;
  const globals = JSON.stringify(DN.loadStoredGlobalPerkRatings()), profiles = JSON.stringify(DN.loadProfilePerkOverrides(DN.activeProfileId()));
  for(let i=0;i<10;i++) document.getElementById('preset-add').click();
  check('More than ten strategies can be created', DN.loadStrategies().strategies.length === 11);
  const selected = DN.activeStrategyId();
  const name = document.getElementById('preset-name'); name.value='Browser fixture strategy'; name.dispatchEvent(new Event('input',{bubbles:true}));
  check('Renaming remains a draft until saved', DN.activeStrategy().name !== name.value && !document.getElementById('army-save').disabled);
  document.getElementById('army-save').click();
  check('Saving persists strategy name', DN.activeStrategy().name === 'Browser fixture strategy');
  let input = document.querySelector('#unit-grid input'); const family=input.dataset.unit; input.checked=true; input.dispatchEvent(new Event('change',{bubbles:true}));
  check('Troop draft does not mutate saved army', !DN.activeStrategy().units.includes(family));
  check('Army has one loadout selector and no advanced management controls', !document.getElementById('strategy-select') && !document.getElementById('strategy-duplicate') && !document.getElementById('strategy-favorite') && !document.getElementById('strategy-archive') && !document.getElementById('strategy-earlier') && !document.getElementById('strategy-later') && !document.getElementById('strategy-archived'));
  const other=DN.loadStrategies().strategies.find(s=>s.id!==selected).id;
  const switchTo = id => document.querySelector('[data-strategy-id="'+id+'"]').click();
  async function answer(value) {
    const dialog=await waitFor(()=>document.querySelector('dialog[open]'));
    dialog.querySelector('[value="'+value+'"]').click();
    await new Promise(r=>setTimeout(r,30));
  }
  switchTo(other);
  await answer('cancel');
  check('Cancelled strategy switch preserves active strategy and draft', DN.activeStrategyId()===selected && document.querySelector('[data-unit="'+family+'"]').checked);
  switchTo(other);
  await answer('save');
  check('Save before switching persists the old loadout', DN.activeStrategyId()===other && DN.loadStrategies().strategies.find(s=>s.id===selected).units.includes(family));
  switchTo(selected);
  check('Saving persists troop selection', DN.activeStrategy().units.includes(family));
  DN.saveStrategyOverrides(selected, {'Heavy Tank Damage':{offensive:3}});
  input=document.querySelector('[data-unit="'+family+'"]'); input.click();
  switchTo(other);
  await answer('discard');
  switchTo(selected);
  check('Discard before switching restores saved troops when revisiting', document.querySelector('[data-unit="'+family+'"]').checked);
  document.querySelector('[data-unit="'+family+'"]').click();
  document.getElementById('army-discard').click();
  await answer('discard');
  check('Revert restores the saved loadout', document.querySelector('[data-unit="'+family+'"]').checked && document.getElementById('army-save').disabled);
  const draftName=document.getElementById('preset-name'); draftName.value=''; draftName.dispatchEvent(new Event('input',{bubbles:true}));
  switchTo(other);
  await answer('save');
  check('Invalid save keeps dialog, active loadout and draft intact', !!document.querySelector('dialog[open]') && DN.activeStrategyId()===selected && document.getElementById('preset-name').value==='' && !document.querySelector('dialog[open] .error').hidden);
  await answer('cancel');
  draftName.value='Pending rename'; draftName.dispatchEvent(new Event('input',{bubbles:true}));
  const originalSet=Storage.prototype.setItem; Storage.prototype.setItem=()=>{throw new Error('Fixture loadout storage full');};
  switchTo(other);
  await answer('save');
  check('Failed save blocks switching and preserves draft', !!document.querySelector('dialog[open]') && DN.activeStrategyId()===selected && document.getElementById('preset-name').value==='Pending rename');
  Storage.prototype.setItem=originalSet;
  await answer('discard');
  switchTo(selected);
  document.querySelector('[data-unit="'+family+'"]').click();
  const navigation=document.querySelector('a[href="ratings.html"]'); navigation.click();
  await answer('cancel');
  check('Cancelled page navigation keeps the unsaved draft', location.pathname.endsWith('army.html') && !document.getElementById('army-save').disabled);
  document.getElementById('army-discard').click(); await answer('discard');
  document.getElementById('preset-add').click();
  const created=DN.activeStrategyId();
  check('New loadout starts empty and leaves existing overrides intact', !DN.activeStrategy().units.length && DN.loadStrategies().strategies.find(s=>s.id===selected).overrides['Heavy Tank Damage'].offensive===3);
  document.getElementById('preset-remove').click(); await answer('cancel');
  check('Delete can be cancelled', DN.activeStrategyId()===created);
  document.getElementById('preset-remove').click(); await answer('delete');
  check('Any selected loadout can be deleted', !DN.loadStrategies().strategies.some(s=>s.id===created));
  check('Army editing and switching preserve shared rating layers', globals===JSON.stringify(DN.loadStoredGlobalPerkRatings()) && profiles===JSON.stringify(DN.loadProfilePerkOverrides(DN.activeProfileId())));
  async function frame(file, ready) {
    const iframe=document.createElement('iframe'); iframe.src=file; document.body.appendChild(iframe);
    await waitFor(()=>iframe.contentWindow.DN && ready(iframe.contentDocument)); return iframe;
  }
  const ratingFrame=await frame('ratings.html', d=>d.querySelector('[data-layer="strategy"]'));
  const rw=ratingFrame.contentWindow, rd=ratingFrame.contentDocument; rw.confirm=()=>true;
  let rating=rd.querySelector('[data-layer="strategy"]'), perk=rating.dataset.key, axis=rating.dataset.axis;
  rating.value='4'; rating.dispatchEvent(new rw.Event('change',{bubbles:true}));
  check('Rating grid saves isolated strategy override', rw.DN.activeStrategy().overrides[perk][axis]===4);
  check('Rating grid explains actual strategy source', [...rd.querySelectorAll('.strategy-rating-source')].some(n=>n.textContent==='Strategy override'));
  check('Strategy override does not alter shared ratings', globals===JSON.stringify(DN.loadStoredGlobalPerkRatings()) && profiles===JSON.stringify(DN.loadProfilePerkOverrides(DN.activeProfileId())));
  const active=rw.DN.activeStrategyId(); rw.DN.setActiveStrategy(other===active ? selected : other);
  check('Another strategy keeps independent override values', !rw.DN.activeStrategy().overrides[perk] || rw.DN.activeStrategy().overrides[perk][axis]!==4);
  rw.DN.setActiveStrategy(active);
  rd.getElementById('ratings-reset-strategy').click();
  check('Strategy reset clears only active strategy override bag', Object.keys(rw.DN.activeStrategy().overrides).length===0);
  const original=rw.Storage.prototype.setItem; rw.Storage.prototype.setItem=()=>{throw new Error('Fixture storage full');};
  rating=rd.querySelector('[data-layer="strategy"]'); rating.value='5'; rating.dispatchEvent(new rw.Event('change',{bubbles:true}));
  check('Storage failure produces a visible error', !rd.getElementById('error').hidden && rd.getElementById('error').textContent.includes('Fixture storage full'));
  rw.Storage.prototype.setItem=original;
  ratingFrame.remove();
  const council=await frame('council-ratings.html', d=>d.getElementById('profile-select'));
  check('Council keeps profile scope without artifact strategy selector', !council.contentDocument.getElementById('strategy-select'));
  council.remove();
  const scanner=await frame('scanner.html', d=>d.getElementById('strategy-select'));
  const sw=scanner.contentWindow, sd=scanner.contentDocument; sw.strategyFixtureSentinel=true;
  const select=sd.getElementById('strategy-select'), next=[...select.options].find(o=>o.value!==select.value).value;
  select.value=next; select.dispatchEvent(new sw.Event('change',{bubbles:true}));
  await new Promise(r=>setTimeout(r,100));
  check('Scanner strategy switch preserves the live page', sw.strategyFixtureSentinel===true && sw.DN.activeStrategyId()===next);
  check('Comparison choices are visible separately from active strategy', sd.querySelectorAll('[data-compare-strategy]').length===sw.DN.loadStrategies().strategies.filter(s=>!s.archived).length);
  scanner.remove();
  const army=await frame('army.html', d=>d.querySelector('#unit-grid input'));
  const aw=army.contentWindow, ad=army.contentDocument;
  const choose=async value=>{
    const dialog=await waitFor(()=>ad.querySelector('dialog[open]'));
    dialog.querySelector('[value="'+value+'"]').click();
    await new Promise(r=>setTimeout(r,40));
  };
  const archivedId=aw.DN.addStrategy('Previously archived army');
  aw.DN.archiveStrategy(archivedId);
  check('Previously archived loadouts remain selectable', !!ad.querySelector('[data-strategy-id="'+archivedId+'"]'));
  ad.querySelector('[data-strategy-id="'+archivedId+'"]').click();
  check('Selecting a previous archive restores its availability', aw.DN.activeStrategyId()===archivedId && !aw.DN.activeStrategy().archived);
  aw.DN.saveStrategies({...aw.DN.loadStrategies(),strategies:[aw.DN.activeStrategy()]});
  ad.getElementById('preset-remove').click(); await choose('delete');
  check('Deleting the final loadout leaves a usable empty loadout', aw.DN.loadStrategies().strategies.length===1 && aw.DN.activeStrategyId()!==archivedId && !aw.DN.activeStrategy().units.length && !!ad.querySelector('#unit-grid input'));
  let childName=ad.getElementById('preset-name'); childName.value='Saved before navigation'; childName.dispatchEvent(new aw.Event('input',{bubbles:true}));
  const navSavedId=aw.DN.activeStrategyId();
  ad.querySelector('a[href="ratings.html"]').click(); await choose('save');
  await waitFor(()=>army.contentWindow.location.pathname.endsWith('ratings.html'));
  check('Save and navigate persists the loadout before leaving', DN.loadStrategies().strategies.find(s=>s.id===navSavedId).name==='Saved before navigation');
  army.src='army.html'; await waitFor(()=>army.contentWindow.location.pathname.endsWith('army.html') && army.contentDocument.querySelector('#unit-grid input'));
  let cw=army.contentWindow, cd=army.contentDocument;
  childName=cd.getElementById('preset-name'); childName.value='Discarded navigation name'; childName.dispatchEvent(new cw.Event('input',{bubbles:true}));
  cd.querySelector('a[href="ratings.html"]').click();
  let dialog=await waitFor(()=>cd.querySelector('dialog[open]')); dialog.querySelector('[value="discard"]').click();
  await waitFor(()=>army.contentWindow.location.pathname.endsWith('ratings.html'));
  check('Discard and navigate leaves saved data unchanged', DN.loadStrategies().strategies.find(s=>s.id===navSavedId).name==='Saved before navigation');
  const originalProfile=DN.activeProfileId(), newProfile=DN.addProfile('Loadout profile switch');
  army.src='army.html'; await waitFor(()=>army.contentWindow.location.pathname.endsWith('army.html') && army.contentDocument.querySelector('#unit-grid input'));
  cw=army.contentWindow; cd=army.contentDocument;
  childName=cd.getElementById('preset-name'); childName.value='Saved before profile switch'; childName.dispatchEvent(new cw.Event('input',{bubbles:true}));
  const profilePicker=cd.getElementById('profile-select'); profilePicker.value=newProfile; profilePicker.dispatchEvent(new cw.Event('change',{bubbles:true}));
  dialog=await waitFor(()=>cd.querySelector('dialog[open]'));
  check('Save and discard dialog fits a narrow viewport', dialog.scrollWidth<=dialog.clientWidth && [...dialog.querySelectorAll('button')].every(button=>button.getBoundingClientRect().right<=dialog.getBoundingClientRect().right));
  dialog.querySelector('[value="cancel"]').click();
  await new Promise(r=>setTimeout(r,40));
  check('Cancel profile switch restores selector and preserves draft', cw.DN.activeProfileId()===originalProfile && profilePicker.value===originalProfile && childName.value==='Saved before profile switch');
  profilePicker.value=newProfile; profilePicker.dispatchEvent(new cw.Event('change',{bubbles:true}));
  dialog=await waitFor(()=>cd.querySelector('dialog[open]')); dialog.querySelector('[value="save"]').click();
  await waitFor(()=>army.contentDocument!==cd && army.contentWindow.DN?.activeProfileId()===newProfile && army.contentDocument.querySelector('#unit-grid input'));
  army.contentWindow.DN.setActiveProfile(originalProfile);
  check('Profile switch saves the pending name under the original profile', DN.loadStrategies().strategies.find(s=>s.id===navSavedId).name==='Saved before profile switch');
  army.remove();
  DN.removeProfile(newProfile);
  return {passed:checks.every(c=>c.passed),checks};
})();
