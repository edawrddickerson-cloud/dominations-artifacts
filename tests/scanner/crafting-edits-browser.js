(async()=>{
  const get=id=>document.getElementById('scanner-'+id),checks={};
  const check=(name,value)=>{checks[name]=!!value;if(!value)throw new Error(name);};
  const wait=async fn=>{const deadline=performance.now()+10000;while(!fn()){if(performance.now()>deadline)throw new Error('Timed out');await new Promise(resolve=>setTimeout(resolve,25));}};
  await wait(()=>get('names').children.length);
  get('auto').checked=false;
  const names=['Heavy Tank Damage','Heavy Tank Hitpoints','Fighter Damage','Fighter Hitpoints','Mortar Troop Damage'];
  let hall='war',rows=names.map((name,index)=>({name,value:[1,3,6,3,1][index],known:true,hasPercent:true,unlocked:index<2,tier:['white','green','blue','green','white'][index],tierSource:'starting-percentage',level:1,levelSource:'crafting'}));
  const canvas=document.createElement('canvas');canvas.width=640;canvas.height=360;
  window.DNScannerRecognition.create=()=>({close:async()=>{},recognize:async()=>({valid:true,rows,warnings:[],hall,unlocked:{count:2,states:rows.map(row=>row.unlocked)},artifact:{type:'Weapon',hall}})});
  window.DNScannerReading.update(canvas,{session:1,current:true});get('read').click();
  await wait(()=>get('progress').textContent.startsWith('Finished'));
  const details=get('correct').closest('details');details.open=true;
  check('existing results and comparison layout remains',!!document.querySelector('.scanner-summary-bar') && get('result').querySelectorAll('.scanner-stat-table .scanner-perk').length===5);
  check('fresh craft has five blue reroll dice',get('result').querySelectorAll('.scanner-perk-reroll.is-rerollable').length===5 && get('correct').querySelectorAll('.scanner-perk-reroll.is-rerollable').length===5);
  check('fresh craft reroll summary is explicit',get('reroll-status').textContent==='All 5 stats rerollable');
  check('stars beside scanned titles',get('result').querySelectorAll('.scanner-stat-title button.scanner-perk-unlocked').length===5);
  check('tier edits without upgrade controls',get('correct').querySelectorAll('.scanner-perk-tier').length===5 && !get('correct').querySelector('.scanner-perk-level') && !get('correct').querySelector('.storage-range-edit'));
  const field=get('correct').querySelector('.scanner-edit-row'),value=field.querySelector('.scanner-perk-value'),tier=field.querySelector('.scanner-perk-tier');
  const edit=(input,next)=>{input.value=next;input.dispatchEvent(new Event('input',{bubbles:true}));};
  value.value='';edit(tier,'blue');
  check('War Blue fills 6 percent immediately',value.value==='6');
  edit(tier,'green');
  check('automatic percentage follows tier edits',value.value==='3');
  tier.value='';edit(value,'6');
  check('percentage fills tier immediately',tier.value==='blue');
  check('blue title and bold larger text',get('result').querySelector('.scanner-perk').classList.contains('is-blue') && Number(getComputedStyle(get('result').querySelector('.scanner-stat-title')).fontWeight)>=700);
  tier.value='';edit(value,'');
  check('unknown fields have amber borders',[tier,value].every(input=>input.classList.contains('is-unknown') && getComputedStyle(input).borderTopColor==='rgb(231, 183, 109)'));
  edit(tier,'green');
  get('accept').click();
  check('inferred values validate and update result',!get('warnings').textContent && get('result').querySelector('.scanner-stat-value').textContent==='+3%');
  const resultStar=get('result').querySelector('.scanner-perk-unlocked');resultStar.click();
  check('main-table star updates correction star',field.isConnected===false && get('correct').querySelector('.scanner-perk-unlocked').value==='false');
  get('accept').click();
  check('corrected star and level 1 reach item log',get('result').querySelector('.scanner-perk-unlocked').value==='false' && window.DNScannerCollectionCore && get('item-log').textContent.includes('Heavy Tank Damage'));
  const conflict=get('correct').querySelector('.scanner-edit-row');
  edit(conflict.querySelector('.scanner-perk-value'),'1');edit(conflict.querySelector('.scanner-perk-tier'),'blue');get('accept').click();
  check('conflicting known tier and percentage stay flagged',get('warnings').textContent.includes('Tier and starting percentage conflict'));
  hall='main';rows=names.map(name=>({name,value:null,known:true,hasPercent:false,unlocked:true,level:1,levelSource:'crafting'}));
  window.DNScannerReading.reset();window.DNScannerReading.update(canvas,{session:2,current:true});get('read').click();
  await wait(()=>get('progress').textContent.startsWith('Finished'));
  const mainField=get('correct').querySelector('.scanner-edit-row');edit(mainField.querySelector('.scanner-perk-tier'),'blue');
  check('Main Blue fills 11 percent',mainField.querySelector('.scanner-perk-value').value==='11');
  const dice=mainField.querySelector('.scanner-perk-reroll');dice.click();
  check('blue dice edit changes to unavailable',dice.value==='false' && !dice.classList.contains('is-rerollable'));
  dice.click();
  check('unknown dice get amber border',dice.value==='' && dice.classList.contains('is-unknown') && getComputedStyle(dice).borderTopColor==='rgb(231, 183, 109)');
  dice.click();
  check('dice cycle back to available',dice.value==='true' && dice.dataset.manual==='true');
  check('no horizontal page overflow',document.documentElement.scrollWidth<=innerWidth);
  return {passed:Object.values(checks).every(Boolean),ui:checks};
})()
