(async()=>{
  const checks={};
  const check=(name,result)=>{checks[name]=!!result;if(!result)throw new Error(name);};
  const wait=async fn=>{for(let i=0;i<400;i++){if(fn())return;await new Promise(r=>setTimeout(r,25));}throw new Error('Collection loading timed out');};
  await wait(()=>window.DN);
  const DN=window.DN,rows=await(await fetch('data/artifacts.json')).json();
  const owned=rows.filter(row=>row.grade==='Mythical' && row.hall==='Main').slice(0,3);
  DN.setActiveProfile(DN.addProfile('Slot assignment regression'));
  DN.lsSet(DN.COLLECTED_KEY,JSON.stringify(owned.map(row=>DN.artifactKey(row))));
  DN.saveCollectionUi({hall:'Main',viewMode:'structured',valueMode:'actual'});
  DN.lsSet('dn-artifact-hall-filter','Main');
  const frame=document.createElement('iframe');frame.width=1400;frame.height=1000;frame.src='collection.html';document.body.append(frame);
  await wait(()=>frame.contentDocument?.querySelector('#museum-board [data-action="slot-hall"]'));
  const doc=frame.contentDocument,win=frame.contentWindow;
  const empty=()=>doc.querySelector('#museum-board [data-action="slot-hall"][data-grade="Mythical"]');
  empty().click();
  await new Promise(resolve=>setTimeout(resolve,400));
  check('empty Mythical slot opens visible picker',!doc.getElementById('slot-picker').hidden);
  check('picker occupies comparison panel',doc.querySelector('.collection-summary #slot-picker')!==null && doc.querySelector('.collection-summary').classList.contains('is-visible') && !doc.querySelector('.collection-summary').inert);
  check('comparison hidden while selecting',win.getComputedStyle(doc.querySelector('.collection-comparison')).display==='none');
  const rect=doc.getElementById('slot-picker').getBoundingClientRect();
  check('picker begins inside visible viewport',rect.top>=0 && rect.top<win.innerHeight-100);
  check('owned Mythical artifacts appear in picker',doc.querySelectorAll('#slot-picker [data-action="picker-pick"]').length===owned.length);
  doc.querySelector('#slot-picker [data-action="picker-pick"]').click();
  check('chosen Mythical is assigned',win.DN.loadLoadout().Main.mains.length===1);
  check('picker closes after assignment',doc.getElementById('slot-picker').hidden);
  check('comparison returns after choosing an item',!doc.querySelector('.collection-comparison').hidden && doc.querySelector('.collection-summary').classList.contains('is-visible'));
  empty().click();
  check('second empty slot opens picker',!doc.getElementById('slot-picker').hidden);
  check('assigned artifact excluded',doc.querySelectorAll('#slot-picker [data-action="picker-pick"]').length===owned.length-1);
  doc.querySelector('#slot-picker [data-action="picker-pick"]').click();
  check('second Mythical is assigned',win.DN.loadLoadout().Main.mains.length===2);
  empty().click();doc.querySelector('[data-action="picker-close"]').click();
  check('closing picker collapses empty selection panel',!doc.querySelector('.collection-summary').classList.contains('is-visible') && doc.querySelector('.collection-summary').inert);
  return {passed:true,ui:checks};
})();
