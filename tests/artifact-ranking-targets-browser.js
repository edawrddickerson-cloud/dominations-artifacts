(async () => {
  const checks = [], check = (name, passed) => { checks.push({name, passed: !!passed}); if (!passed) throw Error(name); };
  const waitFor = async fn => { for (let i = 0; i < 240; i++) { if (fn()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw Error('Timed out waiting for rankings'); };
  await waitFor(() => document.querySelector('#tbody tr[data-artifact-id]'));
  const DN = window.DN, purposes = window.DNCraftingPurposes;
  const rankingsKey = 'dn-artifact-ranking-targets';
  check('Strategy controls removed', !document.body.textContent.includes('Compare strategies') && !document.getElementById('priority-strategy-context'));
  check('Empty target list offers creation', !!document.querySelector('.strategy-comparison-options a[href="ratings.html#crafting-purposes"]'));
  const donor = purposes.saveCustom({label: 'Economy donor', category: 'economy', perks: ['All Resources Looted']});
  const target = purposes.saveCustom({label: 'Tank target', category: 'attacking', perks: ['Heavy Tank Damage', 'Heavy Tank Hitpoints'], excludedPerks: ['Heavy Tank Hitpoints'], addOns: {economy: {source: 'target', targetId: donor}}});
  purposes.selectPurpose(donor, true);
  const scannerBefore = JSON.stringify(purposes.settings().selected);
  DN.updateStrategy(DN.activeStrategyId(), {overrides: {'Heavy Tank Damage': {offensive: 1}}});
  const strategiesBefore = JSON.stringify(DN.loadStrategies());
  purposes.setRating('Heavy Tank Damage', 7);
  purposes.setRating('All Resources Looted', 3);
  await waitFor(() => document.querySelector(`[data-ranking-target][value="${target}"]`));
  const choose = (doc, id, selected) => { const input = doc.querySelector(`[data-ranking-target][value="${id}"]`); input.checked = selected; input.dispatchEvent(new Event('change', {bubbles: true})); };
  choose(document, target, true);
  check('Target column is selectable', document.querySelector('th[data-sort="target:' + target + '"]').textContent === 'Tank target');
  check('Scanner selection preserved', JSON.stringify(purposes.settings().selected) === scannerBefore);
  check('Strategies preserved', JSON.stringify(DN.loadStrategies()) === strategiesBefore);
  document.getElementById('hall-main').click();
  const catalog = await (await fetch('data/artifacts.json')).json();
  const records = Array.isArray(catalog) ? catalog : catalog.artifacts;
  const definition = purposes.definitions.find(item => item.id === target);
  const tankRatings = [...document.querySelectorAll('.rating-line[title="Heavy Tank Damage"] [aria-label="Offensive rating"] .perk-rating')];
  check('Main perk ratings use profile values over legacy strategy overrides', tankRatings.length > 0 && tankRatings.every(node => node.textContent === '+7'));
  check('Target resolves exclusions and donor perks', definition.stats.has('Heavy Tank Damage') && !definition.stats.has('Heavy Tank Hitpoints') && definition.stats.has('All Resources Looted'));
  const validateScores = (doc, mode, off, def) => {
    let positive = false;
    for (const tr of doc.querySelectorAll('#tbody tr[data-artifact-id]')) {
      const row = records.find(row => String(row.artifact_id) === tr.dataset.artifactId);
      if (!row) continue;
      const scores = [];
      for (let i = 1; i <= 6; i++) {
        const name = row[`perk_${i}_name`];
        const mag = Math.max(...['base', 'max'].map(key => Math.abs(parseFloat(row[`perk_${i}_${key}`]) || 0)));
        const enabled = purposes.axisFor(name) === 'offensive' ? off : def;
        scores.push(definition.stats.has(name) && enabled ? mag * purposes.ratingOf(name) : 0);
      }
      const expected = mode === 'maxrow' ? Math.max(0, ...scores) : scores.reduce((a, b) => a + b, 0);
      const actual = Number(tr.querySelector('.priority-strategy-score').textContent);
      if (actual !== Math.round(expected * 100) / 100) throw Error('Target score mismatch: ' + row.name);
      positive ||= actual > 0;
    }
    return positive;
  };
  check('Hall scores match included shared perks', validateScores(document, 'combined', true, true));
  const excludedRatings = [...document.querySelectorAll('.rating-line[title="Heavy Tank Hitpoints"] .perk-rating')];
  check('Excluded perks have zero main ratings', excludedRatings.length > 0 && excludedRatings.every(node => node.textContent === '0'));
  const checkMainTotals = () => [...document.querySelectorAll('#tbody tr[data-artifact-id]')].every(tr =>
    Math.round(Number(tr.querySelector('.pref-total-cell .pref-score')?.textContent || 0) * 100) / 100 === Number(tr.querySelector('.priority-strategy-score').textContent));
  check('Main Hall totals use selected target perks', checkMainTotals());
  document.getElementById('score-maxrow').click();
  check('Showcase scores match best included line', validateScores(document, 'maxrow', true, true));
  check('Main Showcase totals use selected target perks', checkMainTotals());
  document.getElementById('sort-off').click();
  check('Off axis toggle updates target scores', !validateScores(document, 'maxrow', false, true));
  document.getElementById('sort-off').click();
  document.querySelector('th[data-sort="target:' + target + '"] button').click();
  const values = [...document.querySelectorAll('.priority-strategy-score')].map(cell => Number(cell.textContent));
  check('Target column sorts descending', values.every((value, i) => !i || value <= values[i - 1]));
  const frame = document.createElement('iframe'); frame.src = 'artifacts.html'; document.body.append(frame);
  await waitFor(() => frame.contentDocument?.querySelector('th[data-sort="target:' + target + '"]'));
  check('Rankings selection survives reload', frame.contentDocument.querySelector(`[data-ranking-target][value="${target}"]`).checked);
  frame.remove();
  purposes.saveCustom({id: target, label: 'Renamed target', category: 'attacking', perks: ['Heavy Tank Damage'], addOns: {economy: {source: 'target', targetId: donor}}});
  await waitFor(() => document.querySelector('th[data-sort="target:' + target + '"]')?.textContent === 'Renamed target');
  check('Target edits refresh the rankings', document.querySelector(`[data-ranking-target][value="${target}"]`).parentElement.textContent.includes('Renamed target'));
  choose(document, donor, true);
  check('Multiple target columns', document.querySelectorAll('th.priority-strategy-heading').length === 2);
  choose(document, target, false);
  choose(document, donor, false);
  check('Clearing targets restores profile-only table', !document.querySelector('th.priority-strategy-heading') && !!document.querySelector('th[aria-sort="descending"]'));
  check('Empty selection saved', DN.lsGet(rankingsKey) === '[]');
  check('Scanner selection remains unchanged', JSON.stringify(purposes.settings().selected) === scannerBefore);
  choose(document, target, true);
  purposes.removeCustom(target);
  await waitFor(() => !document.querySelector(`[data-ranking-target][value="${target}"]`));
  check('Deleted targets remove their columns', !document.querySelector('th.priority-strategy-heading'));
  DN.lsSet(rankingsKey, JSON.stringify([donor]));
  const profileId = DN.activeProfileId();
  const other = DN.addProfile('Other rankings profile');
  DN.setActiveProfile(other);
  check('Rankings selections are scoped to profile', DN.lsGet(rankingsKey) === null);
  DN.setActiveProfile(profileId);
  check('Original profile retains its selection', DN.lsGet(rankingsKey) === JSON.stringify([donor]));
  const ranged = purposes.saveCustom({label: 'Ranged Infantry and Siege', category: 'attacking', selections: ['attack-ranged-infantry', 'attack-ranged-siege']});
  purposes.setRating('Bazooka Damage', 8);
  purposes.setRating('Ranged Infantry Damage', 6);
  DN.lsSet(rankingsKey, '[]');
  window.dispatchEvent(new Event('focus'));
  await waitFor(() => document.querySelector(`[data-ranking-target][value="${ranged}"]`));
  choose(document, ranged, true);
  const bazookaRatings = () => [...document.querySelectorAll('.rating-line[title="Bazooka Damage"] [aria-label="Offensive rating"] .perk-rating')];
  const rangedRatings = [...document.querySelectorAll('.rating-line[title="Ranged Infantry Damage"] [aria-label="Offensive rating"] .perk-rating')];
  check('Ranged-only target zeroes Bazooka ratings', bazookaRatings().length > 0 && bazookaRatings().every(node => node.textContent === '0'));
  check('Ranged-only target retains Ranged Infantry ratings', rangedRatings.length > 0 && rangedRatings.every(node => node.textContent === '+6'));
  choose(document, donor, true);
  const lootRatings = [...document.querySelectorAll('.rating-line[title="All Resources Looted"] [aria-label="Offensive rating"] .perk-rating')];
  check('Multiple targets combine included perks', lootRatings.length > 0 && lootRatings.every(node => node.textContent === '+3') && bazookaRatings().every(node => node.textContent === '0'));
  choose(document, ranged, false);
  choose(document, donor, false);
  check('Clearing targets restores Bazooka profile ratings', bazookaRatings().every(node => node.textContent === '+8'));
  return {passed: checks.every(check => check.passed), checks};
})();
