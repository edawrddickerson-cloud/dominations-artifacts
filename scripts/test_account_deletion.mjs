import assert from 'node:assert/strict';
import {createHandler} from '../supabase/functions/delete-account/handler.mjs';
const id='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222';
const now=Date.parse('2026-10-18T12:00:00Z');
const settings={APP_ORIGINS:'https://planner.example',SUPABASE_URL:'https://project.supabase.co',APP_SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test',APP_SUPABASE_SECRET_KEY:'server-only'};
let deleted=[],fresh=true,authenticated=true,failAnalytics=false,requests=[];
const createClient=(url,key)=>key==='server-only'?{auth:{admin:{async deleteUser(who){deleted.push(who);return {error:null};}}}}:{auth:{async getUser(token){assert.equal(token,'verified-token');return {data:{user:authenticated?{id,last_sign_in_at:new Date(now-(fresh?1000:3600000)).toISOString()}:null},error:null};}}};
const fetchImpl=async(url,options)=>{
  requests.push({url:new URL(url),options});
  if(failAnalytics)return new Response('{}',{status:503});
  if(options.method==='DELETE')return new Response(null,{status:204});
  return Response.json({results:[{id:'person-id'}],next:null});
};
const handler=createHandler({createClient,env:{get:key=>settings[key]},fetchImpl,now:()=>now});
const request=(options={})=>new Request('https://project.supabase.co/functions/v1/delete-account',{method:'POST',headers:{Origin:'https://planner.example',Authorization:'Bearer verified-token','Content-Type':'application/json',...options.headers},body:JSON.stringify(options.body || {confirmation:'DELETE',owner_id:other})});
assert.equal((await handler(request({headers:{Origin:'https://attacker.example'}}))).status,403);
assert.equal((await handler(request({headers:{Authorization:''}}))).status,401);
assert.equal((await handler(request({body:{confirmation:'no'}}))).status,400);
authenticated=false;assert.equal((await handler(request())).status,401);authenticated=true;
fresh=false;assert.equal((await handler(request())).status,409);fresh=true;
assert.equal(deleted.length,0);
settings.APP_ANALYTICS_ENABLED='true';assert.equal((await handler(request())).status,503);assert.equal(deleted.length,0,'missing cleanup configuration cannot silently skip analytics deletion');
settings.POSTHOG_PROJECT_ID='123';settings.POSTHOG_PERSONAL_API_KEY='private-api-key';
failAnalytics=true;assert.equal((await handler(request())).status,502);assert.equal(deleted.length,0,'an unavailable analytics provider does not produce false deletion success');
failAnalytics=false;requests=[];const result=await handler(request());
assert.equal(result.status,200);assert.deepEqual(await result.json(),{deleted:true,analyticsDeletionRequested:true});
assert.deepEqual(deleted,[id],'the verified identity controls deletion, not request owner_id');
assert.equal(requests[0].url.searchParams.get('distinct_id'),'u:'+id);
assert.equal(requests[1].url.searchParams.get('delete_events'),'true');assert.equal(requests[1].url.searchParams.get('delete_recordings'),'true');
assert.equal(result.headers.get('Access-Control-Allow-Origin'),'https://planner.example');
settings.APP_ANALYTICS_ENABLED='false';
delete settings.APP_SUPABASE_PUBLISHABLE_KEY;delete settings.APP_SUPABASE_SECRET_KEY;
settings.SUPABASE_PUBLISHABLE_KEYS=JSON.stringify({default:'sb_publishable_test'});
settings.SUPABASE_SECRET_KEYS=JSON.stringify({default:'server-only'});
assert.equal((await handler(request())).status,200,'the Supabase runtime can supply both keys without copying privileged values');
settings.SUPABASE_PUBLISHABLE_KEYS='invalid';
assert.equal((await handler(request())).status,503,'invalid runtime key configuration fails closed');
console.log('Deletion: origin/method/auth guards, recent sign-in, verified ownership, fail-closed analytics cleanup and accepted asynchronous deletion passed.');
