// Validate the canonical data and emit the browser copy; no frontend inference.
const fs = require("fs");
const path = require("path");
const assert = require("assert");
function parseCsvLine(line) {
  const fields = [];
  let value = "", quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (quoted && line[i + 1] === '"') { value += '"'; i++; }
      else quoted = !quoted;
    } else if (ch === "," && !quoted) { fields.push(value); value = ""; }
    else value += ch;
  }
  fields.push(value);
  return fields;
}
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "data/army_catalog.json"), "utf8");
const catalog = JSON.parse(source);
const types = new Set(catalog.types.map(t => t.id));
const names = new Set(catalog.units.map(u => u.name));
assert.strictEqual(names.size, catalog.units.length, "Duplicate army unit");
for (const unit of catalog.units) {
  assert(types.has(unit.type), unit.name);
  assert(unit.includes.every(name => names.has(name)), unit.name);
}
for (const [name, scope] of Object.entries(catalog.perk_scopes)) {
  assert(["unit", "type", "independent"].includes(scope.kind), name);
  if (scope.kind === "unit") assert(names.has(scope.unit), name);
  if (scope.kind === "type") assert(types.has(scope.type), name);
}
const rows = fs.readFileSync(path.join(root, "data/perk_name_mapping.csv"), "utf8")
  .trim().split(/\r?\n/).slice(1).map(parseCsvLine);
const defaults = JSON.parse(fs.readFileSync(path.join(root, "data/perk_rating_defaults.json"), "utf8"));
for (const name of [...rows.map(row => row[1]), ...Object.keys(defaults)]) {
  assert(catalog.perk_scopes[name], `Add canonical army scope for ${name}`);
}
for (const [alias, target] of Object.entries(catalog.perk_aliases)) {
  assert(catalog.perk_scopes[target], alias);
}
for (const row of rows) {
  if (row[0] !== row[1]) assert.strictEqual(catalog.perk_aliases[row[0]], row[1], row[0]);
}
const artifacts = JSON.parse(fs.readFileSync(path.join(root, "data/artifacts.json"), "utf8"));
const seenSigns = new Map();
for (const [name, sign] of Object.entries(catalog.perk_signs || {})) {
  assert([-1, 1].includes(sign), `Invalid fixed sign for ${name}`);
  if (/^invading\b/i.test(name)) assert.strictEqual(sign, -1, `Invading stat must be negative: ${name}`);
}
for (const artifact of artifacts) {
  for (let i = 1; i <= 6; i++) {
    const name = artifact[`perk_${i}_name`];
    if (name) assert(catalog.perk_scopes[catalog.perk_aliases[name] || name],
      `Add canonical army scope for artifact perk ${name}`);
    const canonical = catalog.perk_aliases[name] || name;
    const sign = /^invading\b/i.test(canonical) ? -1 : catalog.perk_signs?.[canonical];
    if (name) for (const suffix of ['base', 'max']) {
      const raw = artifact[`perk_${i}_${suffix}`];
      if (raw === '' || raw == null || !Number.isFinite(Number(raw))) continue;
      const actual = Math.sign(Number(raw));
      assert(actual !== 0, `Zero benefit value for ${artifact.name}: ${canonical}`);
      if (seenSigns.has(canonical)) assert.strictEqual(actual, seenSigns.get(canonical),
        `Mixed signs for ${canonical}: ${artifact.name}`);
      seenSigns.set(canonical, actual);
    }
    if (sign) for (const suffix of ['base', 'max']) {
      const raw = artifact[`perk_${i}_${suffix}`];
      if (raw !== '' && raw != null) assert(Number(raw) * sign > 0,
        `Wrong sign for ${artifact.name}: ${canonical} ${suffix}=${raw}`);
    }
  }
}
fs.writeFileSync(path.join(root, "ui/data/army_catalog.json"), source);
fs.writeFileSync(path.join(root, "ui/data/army_catalog.js"),
  "// Generated by scripts/export_army_catalog.js; edit data/army_catalog.json.\n" +
  "window.DN_ARMY_CATALOG = " + JSON.stringify(catalog) + ";\n");
