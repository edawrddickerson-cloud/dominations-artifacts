const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const core=require('../ui/research-planner-core.js');
const data=JSON.parse(fs.readFileSync(path.join(__dirname,'../ui/data/research_planner.json'),'utf8'));
const find=(name,line)=>data.entries.find(e=>e.name===name&&(!line||e.line===line));
const matching=(entry,stage,focus)=>entry.stages[stage-1].matches.some(m=>m.focus===focus);
assert.equal(data.entries.length,420);
assert(matching(find('Cast Iron'),1,'APC'));
assert(!matching(find('Cast Iron'),2,'APC'));
assert(matching(find('Cast Iron'),4,'APC'));
assert(matching(find('Cast Iron'),5,'APC'));
assert(!matching(find('Aviation'),3,'APC'),'Air capacity must not be offered for APCs');
assert(matching(find('Standing Army'),4,'APC'));
assert(!matching(find('Heavy Infantry Defender Damage','Catherine the Great')||find('Damage','Catherine the Great'),1,'APC'),'Defender damage is not attacking infantry damage');
assert(!matching(find('Chivalry'),1,'APC'),'Do not copy the APC page’s conflicting Chivalry claim');
const apc=find('APC Hitpoints','Sally Ride'),tesla=find('APC Deployment Speed','Nikola Tesla');
assert.equal(apc.minimum_age_index,11);assert.equal(tesla.minimum_age_index,16);
assert.equal(tesla.stages[0].matches.find(m=>m.focus==='APC').relation,'direct');
let state=core.normalize(data,null);
assert(!core.results(data,state).some(r=>r.status==='Ready'));
state.age=11;state.buildings.University=6;state.buildings.Library=11;
assert(!core.results(data,state).some(r=>r.entry.id===tesla.id));
assert(core.results(data,state,{future:true}).some(r=>r.entry.id===tesla.id&&r.status==='Later age'));
state.levels[apc.id]=0;
assert.equal(core.status(data,apc,apc.stages[0],state), 'Prerequisites needed');
for(const r of apc.stages[0].requires)state.levels[r.any[0].id]=r.any[0].level;
assert.equal(core.status(data,apc,apc.stages[0],state), 'Ready');
state.buildings.University=5;assert.equal(core.status(data,apc,apc.stages[0],state),'Building upgrade needed');state.buildings.University=6;
const computing=find('Computing'),row=computing.stages[0];
state.levels[computing.id]=0;
assert(row.requires.some(r=>r.any.length===2),'Computing has OR prerequisites');
const alternatives=row.requires.find(r=>r.any.length===2).any;
state.levels[alternatives[1].id]=alternatives[1].level;
assert.equal(core.status(data,computing,row,state), 'Ready','Either OR prerequisite must suffice');
const cast=find('Cast Iron');state.levels[cast.id]=1;
const castResult=core.results(data,state).find(r=>r.entry.id===cast.id);
assert.equal(castResult.stage.level,4,'Show the next relevant chapter after nonmatching chapters');
assert.equal(castResult.status,'Prerequisites needed','Do not skip chapters 2 and 3');
const disputed=data.entries.find(e=>e.age_status==='conflicting_sources');state.levels[disputed.id]=0;
assert.equal(core.status(data,disputed,disputed.stages[0],state),'Age disputed');
assert(!core.results(data,state,{focus:'all',future:true}).some(r=>r.entry.id===disputed.id));
assert(core.results(data,state,{focus:'all',future:true,disputed:true}).some(r=>r.entry.id===disputed.id));
state.levels[apc.id]=apc.max_level;
assert(!core.results(data,state).some(r=>r.entry.id===apc.id));
assert.equal(core.results(data,state,{finished:true}).find(r=>r.entry.id===apc.id).status,'Complete');
const clean=core.normalize(data,{age:999,levels:{[apc.id]:999,bogus:3},buildings:{University:999}});
assert.equal(clean.age,null);assert.equal(clean.buildings.University,null);assert.equal(core.completed(clean,apc.id),null);
const capstone=find('Archaeology Capstone');
assert.equal(capstone.stages[0].building_level,7,'Full-bookcase gate must also require the effective Library level');
const conditional=find('Fully Loaded Offense').stages[1];
state.age=17;state.buildings.Library=17;state.levels[find('Fully Loaded Offense').id]=1;
assert.equal(core.status(data,find('Fully Loaded Offense'),conditional,state,conditional.matches.find(m=>m.focus==='APC')),'Check conditions');
console.log('PASS: research mappings, linked infantry, age/building gates, unknown progress, OR prerequisites, chapter order, disputed gates and completion');
