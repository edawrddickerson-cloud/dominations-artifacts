/* Prepare a pasteable Dashboard function from the tested canonical sources.
 * No provider access, credentials, application changes or deployment. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const handler=fs.readFileSync(path.join(root,'supabase/functions/delete-account/handler.mjs'),'utf8');
const entry=fs.readFileSync(path.join(root,'supabase/functions/delete-account/index.ts'),'utf8');
const localImport="import {createHandler} from './handler.mjs';";
if(!entry.includes(localImport))throw Error('The function entry point changed; update the Dashboard preparation script.');
const result='/* Generated by scripts/prepare_supabase_dashboard.cjs. Edit canonical sources, then regenerate. */\n'+entry.replace(localImport,handler);
new vm.Script(result.replace(/^import .*;\r?\n/m,'').replace('export function createHandler','function createHandler'));
const directory=path.join(root,'data/temp/supabase-dashboard');
fs.mkdirSync(directory,{recursive:true});
const destination=path.join(directory,'delete-account.ts');fs.writeFileSync(destination,result);
console.log('Dashboard function ready: '+destination);
