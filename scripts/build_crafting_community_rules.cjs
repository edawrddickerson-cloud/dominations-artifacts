/* Generate the reviewed, signed starting-roll registry used by SQL validation.
 * Unknown units/availability and named-artifact ranges are deliberately absent. */
const fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};vm.createContext(context);
for(const file of ['data/artifact_stat_context','crafting-community'])vm.runInContext(fs.readFileSync('ui/'+file+'.js','utf8'),context);
const entries=new Map();
for(const [key,rule] of context.window.DNCraftingCommunity.rules()){
  const [hall,category]=key.split('|');entries.set([hall,category,rule.perk].join('|'),{hall,category,...rule});
}
const quote=s=>"'"+s.replaceAll("'","''")+"'";
const rows=[...entries.values()].sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b))).map(r=>'('+[r.hall,r.category,r.perk].map(quote).join(',')+',array['+r.starts.join(',')+']::numeric[])');
const result='-- Generated by scripts/build_crafting_community_rules.cjs; reviewed local rule set.\ninsert into public.planner_crafting_rules(hall,category,perk,starts) values\n'+rows.join(',\n')+';\n';
const target='supabase/migrations/202610230002_crafting_starting_rules.sql';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==result)throw Error('Crafting SQL rules differ from browser rules.');}else fs.writeFileSync(target,result);
console.log(entries.size+' reviewed signed starting rules.');
