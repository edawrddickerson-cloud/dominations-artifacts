/* Local lifetime totals follow encounters, not OCR attempts or mutable stats. */
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{},document:{getElementById:()=>null},Date};vm.createContext(context);
vm.runInContext(fs.readFileSync('ui/scanner-collection.js','utf8'),context);
const create=context.window.DNScannerCollectionCore.createCollector;
const copy=value=>JSON.parse(JSON.stringify(value));
const read=(hall='main',unlocked=2)=>({valid:true,hall,artifact:{type:'Weapon'},unlocked:{count:unlocked},rows:Array.from({length:5},(_,i)=>({name:'Perk '+i,value:6,known:true,hasPercent:true}))});
let log=create();
const totals=()=>copy(log.summary().lifetime);
assert.deepEqual(totals(),{logged:0,kept:0,main:0,war:0,threeUnlocked:0});
const options={encounterId:'one',profileKey:'collection:main',steadyState:true};
for(let i=0;i<22;i++)log.recordItem(read(),1,options);
assert.equal(totals().logged,1,'OCR retries count one logged encounter');
assert.equal(log.summary().sinceLastKept,1,'retries count once before the first Keep');
log.recordItem(read('main',3),1,options);
assert.equal(totals().threeUnlocked,1,'a better star read updates its existing contribution');
log.recordItem(read('main',2),1,options);
assert.equal(totals().threeUnlocked,0,'a corrected star count does not inflate lifetime stats');
log.recordItem(read('war',3),2,{...options,encounterId:'two',newEncounter:true});
const id=log.summary().items[0].id;
log.updateItem(id,{keptId:'saved-one'});log.updateItem(id,{keptId:'saved-one'});
assert.equal(log.summary().sinceLastKept,0,'Keep resets the counter even for an earlier logged item');
assert.deepEqual(totals(),{logged:2,kept:1,main:1,war:1,threeUnlocked:1});
log=create({initialData:JSON.parse(log.serialize())});
assert.deepEqual(totals(),{logged:2,kept:1,main:1,war:1,threeUnlocked:1},'reload does not recount saved totals');
log.clear();log.clear();
assert.equal(log.summary().itemCount,0);
assert.deepEqual(totals(),{logged:2,kept:1,main:1,war:1,threeUnlocked:1},'clearing history preserves lifetime totals exactly once');
log=create({initialData:log.exportData()});
log.recordItem(read('main',3),3,{encounterId:'three',newEncounter:true});
assert.deepEqual(totals(),{logged:3,kept:1,main:2,war:1,threeUnlocked:2},'new logs extend archived totals');
const exported=log.exportData();exported.lifetimeStatistics.totals.logged=999999;
log=create({initialData:exported});
assert.equal(totals().logged,3,'restoration recomputes visible items rather than trusting exported totals');
const legacy=copy(exported);delete legacy.lifetimeStatistics;
log=create({initialData:legacy});assert.equal(totals().logged,1,'old logs seed totals from the history still available');
legacy.lifetimeStatistics={version:1,archived:{logged:-1,kept:0,main:0,war:0,threeUnlocked:0}};
log=create({initialData:legacy});assert.equal(totals().logged,1,'invalid counters cannot corrupt historical counts');
log=create();log.recordItem(read(),1,{newEncounter:true});
const keptId=log.summary().items[0].id;log.updateItem(keptId,{keptId:'kept-first'});
log.recordItem(read(),2,{newEncounter:true});log.recordItem(read(),2);
assert.equal(log.summary().sinceLastKept,1,'a new craft counts once after Keep');
log.updateItem(keptId,{keptId:'kept-first'});
assert.equal(log.summary().sinceLastKept,1,'repeated Keep metadata does not reset subsequent crafts');
log=create({initialData:JSON.parse(log.serialize())});assert.equal(log.summary().sinceLastKept,1,'the counter survives reopening');
log.clear();log=create({initialData:log.exportData()});assert.equal(log.summary().sinceLastKept,1,'clearing detailed history preserves the counter');
log.recordItem(read(),3,{newEncounter:true});assert.equal(log.summary().sinceLastKept,2);
log.updateItem(log.summary().items[0].id,{keptId:'kept-third'});assert.equal(log.summary().sinceLastKept,0,'the next successful Keep resets the counter');
console.log('Lifetime log totals and crafts since Keep: retry isolation, updated stats, Keep deduplication, reloads, clear, exports and legacy migration passed.');
