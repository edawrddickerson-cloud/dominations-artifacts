/* Positive category evidence for the ratings view only. Never constrains OCR,
 * rerolls or scoring, and never derives ordinary pools from named artifacts. */
'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const context = require('../ui/artifact-stat-context.js').create(require('../data/artifact_stat_context.json'));
const categories = {main: ['Weapon', 'Armor', 'Jewelry', 'Pottery'], war: ['Weapon', 'Armor', 'Equipment']};
function build(exportData, video, source) {
  const pools = Object.fromEntries(Object.entries(categories).map(([hall, types]) => [hall, Object.fromEntries(types.map(type => [type, {}]))]));
  const entry = (hall, type, name) => pools[hall][type][name] ||= {observedItems: 0, reviewedFrames: []};
  for (const item of exportData.items || []) {
    if (item.freshCraft !== true || !pools[item.hall]?.[item.type]) continue;
    const seen = new Set();
    for (const row of item.rows || []) {
      if (!row.known || row.assumed || row.inferred || row.estimated || row.conflict || row.tierConflict || row.outOfRange ||
          row.inferredFields?.some(field => ['name', 'value'].includes(field)) || row.hasPercent === false || !Number.isFinite(row.value)) continue;
      const stat = context.lookup(row.name);
      if (!stat || context.assess(row, {hall: item.hall, type: item.type, freshCraft: true}).issues.length || seen.has(stat.name)) continue;
      seen.add(stat.name);
      entry(item.hall, item.type, stat.name).observedItems++;
    }
  }
  for (const frame of video.cases || []) {
    const type = frame.category.replace(/^War /, '');
    if (!pools[frame.hall]?.[type]) continue;
    for (const [name] of frame.rows) {
      const stat = context.lookup(name);
      if (!stat) continue;
      const evidence = entry(frame.hall, type, stat.name);
      if (!evidence.reviewedFrames.includes(frame.time)) evidence.reviewedFrames.push(frame.time);
    }
  }
  for (const types of Object.values(pools)) for (const [type, perks] of Object.entries(types)) {
    types[type] = Object.fromEntries(Object.entries(perks).sort(([a], [b]) => a.localeCompare(b)));
  }
  return {schema_version: 1, kind: 'observed-crafted-perk-pools', complete: false,
    notes: 'Positive category evidence only. Scanner observations are unverified and may repeat encounters. Unseen stats remain unassigned; named Legendary and Mythical artifacts do not establish crafted pools.',
    sources: {observations: source, reviewed: 'tests/scanner/video/2026-10-16.json'}, pools};
}
function files(data) {
  const json = JSON.stringify(data, null, 2) + '\n';
  return {'data/crafted_perk_pools.json': json, 'ui/data/crafted_perk_pools.json': json,
    'ui/data/crafted_perk_pools.js': '// Generated by scripts/build_crafted_perk_pools.js; positive evidence, incomplete pools.\nwindow.DN_CRAFTED_PERK_POOLS = ' + JSON.stringify(data) + ';\n'};
}
if (require.main === module) {
  const input = process.argv.find(arg => arg.startsWith('--input='))?.slice(8);
  if (!input) throw Error('Use --input=artifact-perk-observations.json to build category evidence.');
  const raw = fs.readFileSync(input), data = JSON.parse(raw);
  if (data.version !== 2 || !Array.isArray(data.items)) throw Error('Expected a version-2 encounter export.');
  const result = build(data, require('../tests/scanner/video/2026-10-16.json'), {
    filename: path.basename(input), exportedAt: data.exportedAt, sha256: crypto.createHash('sha256').update(raw).digest('hex'), items: data.items.length,
  });
  for (const [file, content] of Object.entries(files(result))) {
    const target = path.join(root, file);
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) throw Error('Regenerate ' + file);
    } else fs.writeFileSync(target, content);
  }
  console.log(JSON.stringify(Object.fromEntries(Object.entries(result.pools).map(([hall, types]) => [hall, Object.fromEntries(Object.entries(types).map(([type, perks]) => [type, Object.keys(perks).length]))])), null, 2));
}
module.exports = {build, files};
